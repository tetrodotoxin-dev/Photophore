auto Collector::translate_button(U32 code) -> Key {
  switch (code) {
  case VK_LBUTTON:
    return Key::MousePrimary;
  case VK_RBUTTON:
    return Key::MouseSecondary;
  case VK_MBUTTON:
    return Key::MouseMiddle;
  case VK_XBUTTON1:
    return Key::MouseBack;
  case VK_XBUTTON2:
    return Key::MouseForward;
  default:
    return Key::None;
  }
}

