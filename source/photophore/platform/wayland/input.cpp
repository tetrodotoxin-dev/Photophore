auto Photophore::Platform::Input::translate_button(U32 code)
    -> Perimortem::System::Input::Key {
  switch (code) {
  case BTN_LEFT:
    return Key::MousePrimary;
  case BTN_RIGHT:
    return Key::MouseSecondary;
  case BTN_MIDDLE:
    return Key::MouseMiddle;
  case BTN_SIDE:
  case BTN_BACK:
    return Key::MouseBack;
  case BTN_EXTRA:
  case BTN_FORWARD:
    return Key::MouseForward;
  case BTN_TASK:
    return Key::MouseSix;
  case BTN_0:
    return Key::MouseSeven;
  case BTN_1:
    return Key::MouseEight;
  default:
    return Key::None;
  }
}

